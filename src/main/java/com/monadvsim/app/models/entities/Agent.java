package com.monadvsim.app.models.entities;



public class Agent {
    
    private double x, y;
    
    public Agent(){}

    public double getX() {
        return x;
    }

    public void setX(double x) {
        this.x = x;
    }

    public double getY() {
        return y;
    }

    public void setY(double y) {
        this.y = y;
    }
    
}
